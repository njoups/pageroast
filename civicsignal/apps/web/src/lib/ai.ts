import type { Role } from './api';

export type Sentiment = 'positive' | 'negative' | 'neutral' | 'mixed' | 'unknown';
export type AnalysisMethod = 'llm' | 'baseline' | 'test';

export interface Claim { text: string; kind: 'source_fact' | 'interpretation'; quote?: string | null; supportingMentionIds: string[] }
export interface Summary {
  id: string; scope?: string; status: string; summary_text: string | null; claims: Claim[]; conflicts?: Array<{ description: string; supportingMentionIds: string[] }> | null;
  uncertainty_notes: string[] | null; supporting_mention_ids: string[]; method: 'llm' | 'extractive' | null; provider: string | null; model: string | null;
  prompt_version: string | null; generated_at: string | null; period_start?: string | null; period_end?: string | null; created_at?: string;
  tokens_in?: number | null; tokens_out?: number | null; cost_estimate?: string | null;
}
export interface LedgerEntry {
  id: string; status: string; trigger: string; provider: string | null; model: string | null; method: AnalysisMethod | null;
  prompt_versions: Record<string, string> | null; language: string | null; language_confidence: string | null; language_method: string | null;
  content_status: string | null; stages: Record<string, string>; error: { kind: string; message: string } | null; attempt: number;
  tokens_in: number; tokens_out: number; cost_estimate: string | null; cost_currency: string | null; is_current: boolean;
  queued_at: string; started_at: string | null; finished_at: string | null;
}
export interface MentionAnalysis {
  mention: { id: string; title: string; url: string; publisher: string | null; publisher_domain: string; excerpt: string | null; hasBody: boolean;
    processing_status: string; published_at: string | null; discovered_at: string; duplicate_status: string; language: string | null };
  processing: { status: string; current: LedgerEntry | null; latest: LedgerEntry | null; history: LedgerEntry[] };
  language: { feedDeclared: string | null; detected: string | null; confidence: string | null; method: string | null };
  entities: Array<{ entity_id: string; display_name: string; entity_type: string; mentioned_as: string; evidence_text: string; confidence: string; method: string; model_version: string }>;
  topics: Array<{ topic_key: string; custom_label: string; confidence: string; evidence: string[]; taxonomy_version: string; method: string; model_version: string }>;
  sentiment: Array<{ label: Sentiment; confidence: string; uncertain: boolean; target_type: 'article' | 'entity' | 'topic'; target_label: string | null;
    evidence: { quotes?: string[]; rationale?: string }; text_scope: string; method: string; model_version: string; created_at: string }>;
  summary: Summary | null;
  cluster: { id: string; label: string; member_count: number; independent_count: number; publisher_count: number; confidence: string } | null;
  taxonomy: { version: string; labels: Record<string, string> };
  disclaimer: string;
}

